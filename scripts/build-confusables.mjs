#!/usr/bin/env node
// Builds src/confusables.ts from Unicode's data (UTS #39, "Unicode Security Mechanisms", section 4):
//  - confusables.txt: each confusable code point and its prototype;
//  - UnicodeData.txt: the Latin small capitals (named "LATIN LETTER SMALL CAPITAL X"), which confusables.txt does not
//    map to their letters (it maps some to other lookalikes, U+1D0D to U+028D), so names like "OPERATOR" written in small
//    capitals would pass a skeleton check alone.
//
//   node scripts/build-confusables.mjs                                  fetch the latest release from unicode.org
//   node scripts/build-confusables.mjs <confusables.txt> <UnicodeData.txt> <ReadMe.txt>   build from downloaded files
//
// The module holds only code points, as hex, so no confusable, invisible or right-to-left character is ever written into
// the source. It is server-side only (src/agent-names.ts reads it); nothing in the console imports it.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CONFUSABLES_URL = "https://www.unicode.org/Public/security/latest/confusables.txt";
const UNICODE_DATA_URL = "https://www.unicode.org/Public/UCD/latest/ucd/UnicodeData.txt";
const UCD_README_URL = "https://www.unicode.org/Public/UCD/latest/ucd/ReadMe.txt";
const OUT = fileURLToPath(new URL("../src/confusables.ts", import.meta.url));

const [confusablesPath, unicodeDataPath, readmePath] = process.argv.slice(2);
const read = async (path, url) => (path ? readFileSync(path, "utf8") : await (await fetch(url)).text());
const text = await read(confusablesPath, CONFUSABLES_URL);
const unicodeData = await read(unicodeDataPath, UNICODE_DATA_URL);
const readme = await read(readmePath, UCD_README_URL);
const sha256 = (s) => createHash("sha256").update(s).digest("hex");

const version = text.match(/^# Version: (\S+)/m)?.[1];
const fileDate = text.match(/^# Date: ([^\r\n]+)/m)?.[1];
if (!version || !fileDate) throw new Error("not a confusables.txt: no Version or Date header");
const ucdVersion = readme.match(/version (\d+\.\d+\.\d+) of the/i)?.[1];
if (!ucdVersion) throw new Error("not the UCD ReadMe.txt: no version");

// confusables.txt data lines: <source code point> ; <target code points> ; <type> # comment. Every type maps to the same
// prototype since Unicode 6.3 ("MA"), so the type is not kept.
const entries = [];
for (const raw of text.split(/\r?\n/)) {
  const line = raw.replace(/#.*$/, "").trim();
  if (!line) continue;
  const [source, target] = line.split(";").map((f) => f.trim());
  if (!/^[0-9A-F]{4,6}$/.test(source) || !/^[0-9A-F]{4,6}( [0-9A-F]{4,6})*$/.test(target)) throw new Error(`unexpected line: ${raw}`);
  entries.push(`${source.toLowerCase()}=${target.toLowerCase().replaceAll(" ", ".")}`);
}
if (entries.length < 5000) throw new Error(`only ${entries.length} mappings: the file looks truncated`);

// UnicodeData.txt: <code point>;<name>;... The Latin small capitals of one letter, or of the digraphs AE, OE and OU,
// map to those capital letters. (ETH, EZH and the turned or barred ones have no plain-letter reading and are left out.)
const smallCapitals = [];
for (const raw of unicodeData.split(/\r?\n/)) {
  const [cp, name] = raw.split(";");
  const m = name?.match(/^LATIN LETTER SMALL CAPITAL ([A-Z]|AE|OE|OU)$/);
  if (m) smallCapitals.push(`${cp.toLowerCase()}=${[...m[1]].map((c) => c.charCodeAt(0).toString(16)).join(".")}`);
}
if (smallCapitals.length < 25) throw new Error(`only ${smallCapitals.length} small capitals: UnicodeData.txt looks truncated`);

const chunk = (list) => {
  const lines = [];
  for (let i = 0, line = ""; i < list.length; i++) {
    line += (line ? "," : "") + list[i];
    if (line.length > 100 || i === list.length - 1) {
      lines.push(`  "${line}",`);
      line = "";
    }
  }
  return lines.join("\n");
};

writeFileSync(OUT, `// GENERATED by scripts/build-confusables.mjs. Do not edit by hand; run the script to regenerate.
//
// Confusables: ${CONFUSABLES_URL}
//   Version ${version} (file date ${fileDate}), SHA-256 ${sha256(text)}, ${entries.length} mappings.
// Small capitals: ${UNICODE_DATA_URL}
//   UCD ${ucdVersion}, SHA-256 ${sha256(unicodeData)}, ${smallCapitals.length} letters named "LATIN LETTER SMALL CAPITAL X".
// Generated: ${new Date().toISOString().slice(0, 10)}
//
// Unicode data (c) Unicode, Inc., used under the Unicode License (https://www.unicode.org/terms_of_use.html).
//
// "source=target" pairs in hex, the target's code points joined by ".", pairs joined by ",".

export const CONFUSABLES_VERSION = "${version}";
export const UCD_VERSION = "${ucdVersion}";

const DATA = [
${chunk(entries)}
].join(",");

/** Latin small capitals (by their Unicode names) to the capital letters they are. */
const SMALL_CAPITALS = [
${chunk(smallCapitals)}
].join(",");

const decode = (data: string) => {
  const map = new Map<number, string>();
  for (const pair of data.split(",")) {
    const [source, target] = pair.split("=");
    map.set(parseInt(source, 16), String.fromCodePoint(...target.split(".").map((h) => parseInt(h, 16))));
  }
  return map;
};

let table: Map<number, string> | undefined;
/** Code point -> prototype string (confusables.txt), decoded once on first use. */
export function confusablePrototypes(): ReadonlyMap<number, string> {
  return (table ??= decode(DATA));
}
let capitals: Map<number, string> | undefined;
/** Latin small capital -> its capital letter(s), decoded once on first use. */
export function smallCapitalLetters(): ReadonlyMap<number, string> {
  return (capitals ??= decode(SMALL_CAPITALS));
}
`);
console.log(`wrote ${OUT}: confusables ${version} (${entries.length}), UCD ${ucdVersion} small capitals (${smallCapitals.length})`);
