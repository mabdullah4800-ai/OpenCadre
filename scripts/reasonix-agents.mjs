#!/usr/bin/env node
// Per-folder OpenCadre identity for Reasonix sessions. Zero dependencies, Node 20+.
//
// Why this exists: OpenCadre identity is per agent key, but Reasonix resolves MCP servers as
// flag > ./reasonix.toml > <Reasonix home>/config.toml. A machine-wide opencadre entry therefore
// gives EVERY session the SAME identity, so concurrent sessions read each other's mail. Putting the
// opencadre entry in a folder's own reasonix.toml makes that folder its own agent.
//
// The isolation is hard, not advisory: a folder whose key is wrong fails closed (the MCP server
// errors on initialize) instead of silently falling back to the machine-wide key. Verified by
// probe, so one folder can never answer as another agent's identity.
//
//   node scripts/reasonix-agents.mjs add <AgentName> --key agt_... [--dir DIR] [--hub URL]
//   node scripts/reasonix-agents.mjs list   [--root DIR]
//   node scripts/reasonix-agents.mjs verify [<AgentName>] [--root DIR]
//
// Keys are never printed: every report shows a fingerprint only. `verify` is the check that
// matters — it asserts each folder resolves to a DISTINCT agent, which is the property that
// stops sessions stealing each other's mail.

import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
// The Reasonix-home rule is IMPORTED, not copied. This file used to carry its own copy, and the
// inheritance check below compares a folder's resolver `source` against that path - so a copy that
// drifted would not error, it would report NOTHING inherited, silently. resolveFolderAgent and
// reasonixHome are now the same module's pair, which is what makes that comparison sound.
import { reasonixHome, resolveFolderAgent } from "./reasonix-opencadre-hook.mjs";
import { pathToFileURL } from "node:url";

const DEFAULT_HUB = "https://app.opencadre.example";
const DEFAULT_ROOT = ".worktrees";
const TIMEOUT_MS = 15_000;

/** `name = "opencadre"` under [[plugins]], plus the Bearer token of its headers. */
const OPEN_PLUGIN = /^\s*\[\[plugins\]\]\s*$/;

const fingerprint = (key) => (key ? `${key.slice(0, 8)}…${key.slice(-4)} (len ${key.length})` : "(none)");
const redact = (text, key) => {
  let out = String(text);
  if (key) out = out.split(key).join("[redacted]");
  return out.replace(/\b(agt|dev|org|ocd)_[A-Za-z0-9_-]{6,}/g, "$1_[redacted]");
};

const usage = (code = 1) => {
  process.stderr.write(
    "usage: reasonix-agents add <AgentName> --key <agt_...> [--dir DIR] [--hub URL]\n" +
      "       reasonix-agents list [--root DIR]\n" +
      "       reasonix-agents verify [<AgentName>] [--root DIR]\n",
  );
  process.exit(code);
};

export function parseArgs(argv) {
  const flags = {};
  const positional = [];
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg.startsWith("--")) flags[arg.slice(2)] = argv[i + 1]?.startsWith("--") ? true : argv[++i];
    else positional.push(arg);
  }
  return { flags, positional };
}

/** Replaces the opencadre [[plugins]] block in place, or appends one, leaving every other
 * table untouched. A [[plugins]] block ends at the next top-level header. */
function replaceOpencadreBlock(text, block) {
  const lines = text.split(/\r?\n/);
  let start = -1;
  let end = lines.length;
  for (let i = 0; i < lines.length && start < 0; i += 1) {
    if (!OPEN_PLUGIN.test(lines[i])) continue;
    let j = i + 1;
    while (j < lines.length && !/^\s*\[/.test(lines[j])) j += 1;
    if (/name\s*=\s*"opencadre"/.test(lines.slice(i + 1, j).join("\n"))) {
      start = i;
      end = j;
    }
  }
  if (start < 0) {
    const base = text.replace(/\s*$/, "");
    return `${base ? `${base}\n\n` : ""}${block}\n`;
  }
  const before = lines.slice(0, start).join("\n").replace(/\s*$/, "");
  const after = lines.slice(end).join("\n").replace(/^\s+/, "");
  return `${[before, block, after].filter((p) => p !== "").join("\n\n")}\n`;
}

/** The opencadre [[plugins]] block. TOML basic strings share JSON's escaping for these values. */
export function opencadreBlock({ hub, key }) {
  const str = (s) => JSON.stringify(s);
  return [
    "[[plugins]]",
    'name    = "opencadre"',
    'type    = "http"',
    `url     = ${str(`${hub.replace(/\/+$/, "")}/mcp`)}`,
    `headers = { Authorization = ${str(`Bearer ${key}`)} }`,
    "",
    "# A folder with this block IS this agent: Reasonix prefers ./reasonix.toml over the",
    "# machine-wide config, and a wrong key fails closed rather than borrowing the machine key.",
    "# Generated by scripts/reasonix-agents.mjs — do not commit (it carries a live key).",
  ].join("\n");
}

/** The opencadre entry this folder would resolve, or null. Never logs the key. */
export function readFolderAgent(file) {
  if (!existsSync(file)) return null;
  const text = readFileSync(file, "utf8");
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    if (!OPEN_PLUGIN.test(lines[i])) continue;
    const block = [];
    for (let j = i + 1; j < lines.length && !/^\s*\[/.test(lines[j]); j += 1) block.push(lines[j]);
    const body = block.join("\n");
    if (!/name\s*=\s*"opencadre"/.test(body)) continue;
    return {
      file,
      hub: body.match(/^\s*url\s*=\s*["']([^"']+)["']/m)?.[1]?.replace(/\/mcp$/, "") ?? null,
      key: body.match(/Bearer\s+([\w-]+)/)?.[1] ?? null,
    };
  }
  return null;
}

export function discover(root) {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => ({ name: e.name, dir: join(root, e.name), agent: readFolderAgent(join(root, e.name, "reasonix.toml")) }))
    .filter((f) => f.agent?.key);
}

/** Folders under `root` that INHERIT the machine-wide agent rather than owning a key.
 *
 * `discover()` cannot answer this: it returns only folders that already carry a reasonix.toml
 * with an OpenCadre block, so a folder that owns nothing is ABSENT from its result rather than
 * reported as inherited. That is the trap this names - Reasonix resolves
 * `flag > ./reasonix.toml > <Reasonix home>/config.toml`, so the third step always succeeds on a
 * machine with a machine-wide entry, and every such folder silently becomes the SAME agent.
 *
 * The identifying property is deliberately NOT "has no reasonix.toml": a folder can carry one
 * and still resolve globally if that file holds no OpenCadre block. It is the resolver's own
 * `source` - the folder's file, or the machine-wide config path.
 *
 * Folder names only. Keys are never read here, let alone printed.
 */
export function inheritedFolders(root, home = reasonixHome()) {
  if (!existsSync(root)) return [];
  // ONE value, used for both the comparison and the resolver call below. It used to be computed
  // from this file's own rule here while `resolveFolderAgent` re-derived it from the hook's, so the
  // two agreed only for as long as the copies happened to match. Now they cannot differ.
  const globalConfig = join(home, "config.toml");
  const out = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    let agent = null;
    try {
      agent = resolveFolderAgent(join(root, entry.name), home);
    } catch {
      continue; // Unreadable or malformed is not this check's business to call inherited.
    }
    if (agent && agent.source === globalConfig) out.push(entry.name);
  }
  return out;
}

async function hubGet(base, path, key) {
  const res = await fetch(`${base}${path}`, {
    headers: { authorization: `Bearer ${key}` },
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  const data = await res.json().catch(() => ({}));
  return { ok: res.ok, status: res.status, data };
}

function add({ positional, flags }) {
  const name = positional[0];
  const key = typeof flags.key === "string" ? flags.key : "";
  if (!name || !key) usage();
  if (!/^agt_[A-Za-z0-9_-]{8,}$/.test(key)) {
    process.stderr.write("That does not look like an agent key (agt_…). Nothing was written.\n");
    process.exit(1);
  }
  const hub = typeof flags.hub === "string" ? flags.hub : DEFAULT_HUB;
  const dir = resolve(typeof flags.dir === "string" ? flags.dir : join(DEFAULT_ROOT, name));
  const file = join(dir, "reasonix.toml");
  const before = existsSync(file) ? readFileSync(file, "utf8") : "";
  const after = replaceOpencadreBlock(before, opencadreBlock({ hub, key }));
  mkdirSync(dir, { recursive: true });
  // Owner-only: the file carries a live key.
  writeFileSync(file, after, { mode: 0o600 });
  try { chmodSync(file, 0o600); } catch { /* best effort on Windows */ }

  const isWorktree = existsSync(join(dir, ".git"));
  process.stdout.write(
    `Wrote ${file}\n` +
      `  agent key : ${fingerprint(key)}\n` +
      `  hub       : ${hub}\n` +
      `  folder    : ${dir}\n` +
      (isWorktree ? "" : `  note      : not a git worktree — "do not edit another agent's worktree" is by convention only here\n`) +
      `\nOpen a Reasonix session IN THAT FOLDER; it will resolve as this agent, not as the machine-wide one.\n`,
  );
}

async function verify({ positional, flags }) {
  const root = resolve(typeof flags.root === "string" ? flags.root : DEFAULT_ROOT);
  const wanted = positional[0];
  const found = discover(root).filter((f) => !wanted || f.name === wanted);
  if (found.length === 0) {
    process.stderr.write(`No folders with an opencadre block under ${root}. Run "add" first.\n`);
    // NOT an immediate exit: a folder with no block of its own is exactly the case that
    // INHERITS the machine-wide agent, so the inherited check below is the more useful answer
    // here. Exiting first would hide the finding in the one situation it exists to name.
    const inheritedOnly = inheritedFolders(root).filter((n) => !wanted || n === wanted);
    if (inheritedOnly.length > 0) {
      process.stdout.write(
        `\nINHERITED the machine-wide agent (${inheritedOnly.length}): ${inheritedOnly.join(", ")}\n` +
          `  These folders carry no OpenCadre block of their own, so they resolve to ${join(reasonixHome(), "config.toml")}.\n` +
          `  They will act as (and read the mail of) whichever agent that file names. Give each its own key with "add".\n`,
      );
    }
    process.exit(1);
  }
  const rows = [];
  for (const f of found) {
    const { agent } = f;
    let identity = { ok: false };
    try {
      identity = await hubGet(agent.hub ?? DEFAULT_HUB, "/v1/me", agent.key);
    } catch (err) {
      identity = { ok: false, status: redact(err.message, agent.key) };
    }
    rows.push({
      folder: f.name,
      key: fingerprint(agent.key),
      status: identity.ok ? "reachable" : `FAILED (${identity.status ?? "unreachable"})`,
      agent: identity.ok ? identity.data.agentName : "-",
      id: identity.ok ? identity.data.agentId : "-",
    });
  }
  const width = Math.max(...rows.map((r) => r.folder.length), 6);
  process.stdout.write(`${"FOLDER".padEnd(width)}  ${"KEY".padEnd(24)}  ${"STATUS".padEnd(12)}  AGENT\n`);
  for (const r of rows) process.stdout.write(`${r.folder.padEnd(width)}  ${r.key.padEnd(24)}  ${r.status.padEnd(12)}  ${r.agent}\n`);

  const ids = rows.filter((r) => r.id !== "-").map((r) => r.id);
  const distinct = new Set(ids).size;
  const failed = rows.filter((r) => r.status !== "reachable").length;
  process.stdout.write(
    `\n${rows.length} folder(s): ${ids.length} reachable, ${failed} failed, ${distinct} distinct agent identity(ies).\n`,
  );
  // Every finding is collected and reported BEFORE the single exit at the end. Reporting each
  // one with its own early process.exit() meant a guard could fire first and hide the others
  // completely — the inherited-folder finding was unreachable on any machine whose visible
  // folders failed to authenticate, which is the common case, not the edge case.
  let bad = failed > 0;

  if (ids.length > 1 && distinct !== ids.length) {
    process.stdout.write("WARNING: two folders resolve to the SAME agent — they will steal each other's mail. Give each its own key.\n");
    bad = true;
  }

  // Folders owning no key are invisible to every check above, yet they resolve to the
  // machine-wide agent and therefore share one identity with each other.
  const inherited = inheritedFolders(root).filter((n) => !wanted || n === wanted);
  if (inherited.length > 0) {
    process.stdout.write(
      `\nINHERITED the machine-wide agent (${inherited.length}): ${inherited.join(", ")}\n` +
        `  These folders carry no OpenCadre block of their own, so they resolve to ${join(reasonixHome(), "config.toml")}.\n` +
        `  They will act as (and read the mail of) whichever agent that file names. Give each its own key with "add".\n`,
    );
    bad = true;
  }

  if (bad) process.exit(1);
  process.stdout.write("OK: every reachable folder is a distinct agent (no mail stealing between them).\n");
}

function list({ flags }) {
  const root = resolve(typeof flags.root === "string" ? flags.root : DEFAULT_ROOT);
  const found = discover(root);
  if (found.length === 0) {
    process.stdout.write(`No folders with an opencadre block under ${root}.\n`);
    return;
  }
  for (const f of found) {
    process.stdout.write(`${f.name.padEnd(20)}  ${fingerprint(f.agent.key).padEnd(24)}  ${f.agent.hub ?? DEFAULT_HUB}\n`);
  }
}

// pathToFileURL, not a hand-built file:// string: only it maps C:\x to file:///C:/x on Windows.
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const parsed = parseArgs(process.argv.slice(2));
  const command = parsed.positional.shift();
  if (command === "add") add({ ...parsed, positional: parsed.positional });
  else if (command === "verify") await verify(parsed);
  else if (command === "list") list(parsed);
  else usage();
}
